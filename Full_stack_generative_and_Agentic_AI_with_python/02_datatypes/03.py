# Numbers Types: Integers, Boolean, floating, decimal, complex numbers

black_tea = 14
ginger = 3

# addition
total = black_tea + ginger
print(f"Total grams:{total}")

# subtraction
total = black_tea - ginger
print(f"Total grams:{total}")

# Multiplication
total = black_tea * ginger
print(f"Total grams:{total}")

# Division
total = black_tea / ginger
print(f"Total grams:{total}")


