# Numbers Types: Integers, Boolean, floating, decimal, complex numbers

black_tea = 14
ginger = 3

# addition
total = black_tea + ginger
print(f"Total grams:{total}")

# subtraction
total = black_tea - ginger
print(f"Total grams:{total}")

# Multiplication
total = black_tea * ginger
print(f"Total grams:{total}")

# Division
total = black_tea / ginger
print(f"Total grams:{total}")

# Round division
total = black_tea // ginger
print(f"Total grams:{total}")


# remainder
total = black_tea % ginger
print(f"Total grams:{total}")

# exponent
total = black_tea ** ginger
print(f"Total grams:{total}")



# to improve readability od=f big numbers  _ is used
total = 1_0000_0000_0000
print(total)

